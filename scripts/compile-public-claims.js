#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT } = require('../capabilities/registry');
const { buildPublicClaims } = require('../capabilities/public-claims');

const START = '<!-- DESIGNOS_PUBLIC_CLAIMS:START -->';
const END = '<!-- DESIGNOS_PUBLIC_CLAIMS:END -->';
const OUTPUT = path.join(ROOT, 'capabilities/public-claims.json');
const DOCUMENTS = ['README.md', 'ARCHITECTURE.md', 'ROADMAP.md', 'LIMITATIONS.md'];
const WRITE = process.argv.includes('--write');

const stableJson = value => JSON.stringify(value, null, 2) + '\n';

/**
 * Generates the markdown table containing the latest public claims.
 * 
 * @param {Object} claims - The built claims object containing statistics.
 * @returns {string} The formatted markdown block wrapped in claim markers.
 */
function markdown(claims) {
  return `${START}
> Generated by \`npm run claims:update\` from package, registry, recipe, fixture and eval sources.

| Public claim | Generated truth |
|---|---:|
| Version | ${claims.package.version} |
| Rules / providers | ${claims.rules.count} / ${claims.rules.providers} |
| Motion recipes / stacks | ${claims.motion.recipes} / ${claims.motion.stacks} |
| Adapter combinations / browser fixtures | ${claims.motion.adapterCombinations} / ${claims.motion.fixtureScenarios} |
| Browser / source-map assertions | ${claims.motion.browserAssertions} / ${claims.motion.sourceMapAssertions} |
| Runtime dependencies | ${claims.dependencies.runtime} |
| External eval | ${claims.evaluation.externalEval ? `verified (${claims.evaluation.externalEvalRuns})` : 'not verified'} |
| Native evidence | ${claims.nativeEvidence.status} (${claims.nativeEvidence.verifiedDeviceRuns} device runs) |
${END}`;
}

/**
 * Replaces the content between the DESIGNOS_PUBLIC_CLAIMS markers in a source string.
 * Throws an error if the markers are missing or malformed.
 * 
 * @param {string} source - The original file content.
 * @param {string} block - The new content to inject between the markers.
 * @param {string} file - The file path (used for error reporting).
 * @returns {string} The modified source string.
 */
function replaceMarked(source, block, file) {
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${file}: public claim markers missing`);
  return source.slice(0, start) + block + source.slice(end + END.length);
}

/**
 * Injects the updated version and claims summary into the Claude plugin manifest.
 * 
 * @param {Object} claims - The built claims object.
 * @returns {string} The updated JSON string for the plugin manifest.
 */
function expectedPlugin(claims) {
  const file = path.join(ROOT, '.claude-plugin/plugin.json');
  const plugin = JSON.parse(fs.readFileSync(file, 'utf8'));
  plugin.version = claims.package.version;
  plugin.description = `DesignOS ${claims.package.version}: ${claims.rules.count} deterministic rules, ${claims.motion.recipes} motion recipes across ${claims.motion.stacks} stacks, ${claims.motion.fixtureScenarios} browser fixtures, ${claims.dependencies.runtime} runtime dependencies; external eval ${claims.evaluation.externalEval ? 'verified' : 'not yet verified'}, native evidence ${claims.nativeEvidence.status}.`;
  return stableJson(plugin);
}

function websiteBlock(claims) {
  return `${START}
<script id="designos-public-claims" type="application/json">${JSON.stringify(claims)}</script>
<script>(()=>{const claims=JSON.parse(document.getElementById('designos-public-claims').textContent);const values={rules:claims.rules.count,recipes:claims.motion.recipes,stacks:claims.motion.stacks,fixtures:claims.motion.fixtureScenarios,assertions:claims.motion.browserAssertions};for(const [key,value] of Object.entries(values)){const target=document.querySelector('[data-designos-claim="'+key+'"]');if(target)target.textContent=String(value)}})();</script>
${END}`;
}

function expectedWebsite(claims) {
  const file = path.join(ROOT, 'website/index.html');
  let source = replaceMarked(fs.readFileSync(file, 'utf8'), websiteBlock(claims), 'website/index.html');
  const values = {
    rules: claims.rules.count,
    recipes: claims.motion.recipes,
    stacks: claims.motion.stacks,
    fixtures: claims.motion.fixtureScenarios,
    assertions: claims.motion.browserAssertions,
  };
  for (const [key, value] of Object.entries(values)) {
    const pattern = new RegExp(`(<b\\s+data-designos-claim="${key}">)[^<]*(</b>)`);
    if (!pattern.test(source)) throw new Error(`website/index.html: missing visible ${key} claim`);
    source = source.replace(pattern, `$1${value}$2`);
  }
  return source;
}

/**
 * Detects if any documentation files contain "Shipped (vX.Y)" claims that exceed 
 * the current package version, which would indicate a drift or premature release claim.
 * 
 * @param {Object} claims - The built claims object.
 * @returns {string[]} An array of strings describing the detected drifts, if any.
 */
function futureShippedClaims(claims) {
  const [currentMajor, currentMinor] = claims.package.version.split('.').map(Number);
  const findings = [];
  for (const relative of DOCUMENTS) {
    const source = fs.readFileSync(path.join(ROOT, relative), 'utf8');
    for (const match of source.matchAll(/Shipped\s*\(v(\d+)\.(\d+)(?:\.\d+)?[^)]*\)/gi)) {
      const major = Number(match[1]);
      const minor = Number(match[2]);
      if (major > currentMajor || (major === currentMajor && minor > currentMinor)) {
        findings.push(`${relative}: ${match[0]} exceeds package ${claims.package.version}`);
      }
    }
  }
  return findings;
}

/**
 * Compiles all public claims from registry, recipes, and fixtures, 
 * and generates the expected content for all target files.
 * 
 * @returns {{claims: Object, expected: Map<string, string>}} The resolved claims and expected file contents mapped by relative path.
 */
function compile() {
  const claims = buildPublicClaims();
  const expected = new Map();
  expected.set('capabilities/public-claims.json', stableJson(claims));
  for (const document of DOCUMENTS) {
    const file = path.join(ROOT, document);
    expected.set(document, replaceMarked(fs.readFileSync(file, 'utf8'), markdown(claims), document));
  }
  expected.set('.claude-plugin/plugin.json', expectedPlugin(claims));
  expected.set('website/index.html', expectedWebsite(claims));
  return { claims, expected };
}

function main() {
  const { claims, expected } = compile();
  const drift = futureShippedClaims(claims);
  for (const [relative, content] of expected) {
    const file = path.join(ROOT, relative);
    if (WRITE) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
    } else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) drift.push(relative);
  }
  if (WRITE) {
    console.log(`public-claims: generated ${expected.size} targets for DesignOS ${claims.package.version}`);
    return;
  }
  if (drift.length) {
    console.error(`public-claims: drift in ${drift.join(', ')}. Run npm run claims:update.`);
    process.exit(1);
  }
  console.log(`public-claims: clean (${claims.rules.count} rules, ${claims.motion.fixtureScenarios} fixtures, ${claims.motion.browserAssertions} browser assertions)`);
}

if (require.main === module) main();

module.exports = {
  START, END, DOCUMENTS, markdown, replaceMarked, websiteBlock, expectedWebsite,
  futureShippedClaims, compile,
};
