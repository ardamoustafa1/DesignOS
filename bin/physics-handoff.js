#!/usr/bin/env node
'use strict';

/**
 * DesignOS Pointer Velocity Handoff Engine
 * Converts raw pointer events (drag/swipe) into perfectly mapped spring physics initial velocity.
 */

function calculateVelocity(startPos, endPos, durationMs) {
  if (durationMs === 0) return 0;
  // Convert ms to seconds for px/s velocity
  const durationS = durationMs / 1000;
  const distance = endPos - startPos;
  return distance / durationS;
}

function compileHandoffConfig(gestureEvents, targetComponent) {
  if (!gestureEvents || gestureEvents.length < 2) {
    throw new Error('At least two gesture events required to calculate velocity handoff.');
  }
  
  // Grab the last two events to calculate the release velocity
  const releaseEvent = gestureEvents[gestureEvents.length - 1];
  const preReleaseEvent = gestureEvents[gestureEvents.length - 2];
  
  const durationMs = releaseEvent.timestamp - preReleaseEvent.timestamp;
  
  const velocityX = calculateVelocity(preReleaseEvent.x, releaseEvent.x, durationMs);
  const velocityY = calculateVelocity(preReleaseEvent.y, releaseEvent.y, durationMs);
  
  // Generate framework-agnostic physics configuration (targets Framer Motion / GSAP / Spring)
  const physicsConfig = {
    target: targetComponent,
    spring: {
      type: 'spring',
      stiffness: 400,
      damping: 30,
      mass: 1,
      velocity: {
        x: velocityX,
        y: velocityY
      }
    },
    codeEmission: `
// Generated by DesignOS Physics Handoff
const handoffTransition = {
  type: "spring",
  stiffness: 400,
  damping: 30,
  velocity: { x: ${velocityX.toFixed(2)}, y: ${velocityY.toFixed(2)} }
};
    `.trim()
  };
  
  return physicsConfig;
}

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--demo')) {
    const mockEvents = [
      { x: 100, y: 50, timestamp: 1000 },
      { x: 150, y: 55, timestamp: 1016 }, // +16ms
      { x: 250, y: 60, timestamp: 1032 }  // +16ms
    ];
    
    console.log('Calculating physics handoff from mock gesture trace...');
    const result = compileHandoffConfig(mockEvents, 'ModalContainer');
    console.log(JSON.stringify(result, null, 2));
    process.exit(0);
  }
}

if (require.main === module) main();
module.exports = { compileHandoffConfig, calculateVelocity };
